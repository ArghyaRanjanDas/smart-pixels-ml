#!/usr/bin/env python
"""THE flip-flop config wrapper generator for every programmable hls4ml design (A_prog: hls4ml_convert_prog.py,
B_lut_prog: convert_kan_b_prog.py). Weights are top-level ports (BramFactor=0, ARRAY_RESHAPE complete +
ap_stable/ap_none on each weight port); ports.json is written by those conversion scripts.

  python make_cfgwrap.py <prj_dir> <top> <ports.json> <out_dir> [tb_x.npy tb_y.npy N]

Weight values are read from firmware/weights/<name>.txt when present (full precision), else <name>.h; every value
is asserted to lie on its ap_fixed grid. Verify the generated wrapper with the xsim testbench below and
  python cosim_check.py --raw <out_dir>/tb_out.txt tb_y.npy --frac-bits F --n N

Writes into <out_dir>:
  <top>_cfgwrap.v   module <top>_cfgwrap: all weight/table bits live in ONE flip-flop shift register
                    reg [NCFG-1:0] cfg, loaded byte-serially (cfg_we, cfg_din[7:0]):
                        always @(posedge ap_clk) if (cfg_we) cfg <= {cfg_din, cfg[NCFG-1:8]};
                    after NCFG/8 writes, byte k of the image sits at cfg[8k+7:8k]. Weight ports are
                    packed in ports.json order from the LSB; element i of an array of width W sits at
                    bits [W*i+W-1 : W*i] of that port (Vitis ARRAY_RESHAPE complete order).
  <top>_cfg.hex     the trained weights as the byte stream (one hex byte per line, first byte first).
  cfg_map.json      bit ranges of every weight port inside cfg.
  tb_<top>_cfgwrap.v (+ tb_in.hex / tb_expected.txt) an xsim testbench through the wrapper: loads the
                    image, runs N events, prints outputs as raw integers (checked by cosim_check.py --raw).
"""
import os, re, sys, json, glob
import numpy as np

prj, top, ports_json, out = sys.argv[1:5]
ports = json.load(open(ports_json))
os.makedirs(out, exist_ok=True)
vdir = f'{prj}/{top}_prj/solution1/syn/verilog'
vsrc = open(f'{vdir}/{top}.v').read()

# ---- port list of the HLS top
hdr = vsrc[vsrc.index(f'module {top}'):]
hdr = hdr[:hdr.index(';')]
names = [n.strip() for n in hdr[hdr.index('(') + 1:hdr.rindex(')')].split(',')]
decl = {}
for d, w, n in re.findall(r'^\s*(input|output)\s+(\[[^\]]+\])?\s*(\w+)\s*;', vsrc, re.M):
    decl[n] = (d, w.replace(' ', '') if w else '')
assert all(n in decl for n in names), [n for n in names if n not in decl]


def width(n):
    w = decl[n][1]
    if not w:
        return 1
    hi, lo = map(int, re.match(r'\[(\d+):(\d+)\]', w).groups())
    return hi - lo + 1


wnames = [p['name'] for p in ports]
ncfg = sum(p['bits'] for p in ports)
pad = (-ncfg) % 8
NCFG = ncfg + pad
# A weight array reaches the RTL either as ONE bus <name>[bits-1:0] (ARRAY_RESHAPE complete took effect) or split per
# element <name>_0 .. <name>_{n-1} (a layer's ARRAY_PARTITION complete on the same argument overrides the reshape;
# e.g. A_prog's conv weights/biases, B_lut_prog's KAN tables and biases). Both are wired to the same cfg slice.
cmap, off, wconn = {}, 0, []    # wconn: (rtl port, hi, lo)
for p in ports:
    n, W = p['name'], p['width']
    cmap[n] = dict(lo=off, hi=off + p['bits'] - 1, n=p['n'], width=W, type=p['type'], layer=p['layer'])
    if n in decl:
        assert decl[n][0] == 'input' and width(n) == p['bits'], (n, decl[n], p['bits'])
        assert not any(x.startswith(n + '_') and x[len(n) + 1:].isdigit() for x in names), f'{n}: bus AND split ports'
        wconn.append((n, off + p['bits'] - 1, off)); cmap[n]['rtl'] = 'bus'
    else:
        el = [f'{n}_{i}' for i in range(p['n'])]
        miss = [e for e in el if e not in decl]
        assert not miss, f'weight port {n}: neither a bus nor {p["n"]} element ports (missing {miss[:4]})'
        for i, e in enumerate(el):
            assert decl[e][0] == 'input' and width(e) == W, (e, decl[e], W)
            wconn.append((e, off + W * (i + 1) - 1, off + W * i))
        cmap[n]['rtl'] = 'split'
    off += p['bits']
wset = {c[0] for c in wconn}
assert not [x for x in names if x not in wset and re.match('(' + '|'.join(map(re.escape, wnames)) + r')(_\d+)?_(ce\d*|address\d*|q\d*|ap_vld)$', x)], \
    'weight arrays must be plain wires (no memory interface / handshake)'
clk = 'ap_clk'; rst = 'ap_rst' if 'ap_rst' in decl else ('ap_rst_n' if 'ap_rst_n' in decl else None)
assert clk in decl

# ---- wrapper
others = [n for n in names if n not in wset]
plines = []
for n in others:
    d, w = decl[n]
    plines.append(f'  {d} {w + " " if w else ""}{n}')
plines += ['  input cfg_we', '  input [7:0] cfg_din']
conn = [f'.{n}({n})' for n in others] + [f'.{n}(cfg[{hi}:{lo}])' for n, hi, lo in wconn]
wrap = f"""// AUTO-GENERATED by scripts/synth/hls4ml_common/make_cfgwrap.py: config register file for {top}.
// {NCFG} flip-flops ({ncfg} weight/table bits{f' + {pad} pad' if pad else ''}) = {NCFG // 8} bytes, loaded byte-serially with
// cfg_we/cfg_din (first byte written ends at cfg[7:0]). They drive the ap_stable weight ports of the
// Vitis HLS core directly, so the datapath sees registers, never memories. Bit map: cfg_map.json.
module {top}_cfgwrap(
{(',' + chr(10)).join(plines)});
  reg [{NCFG - 1}:0] cfg;
  always @(posedge {clk}) if (cfg_we) cfg <= {{cfg_din, cfg[{NCFG - 1}:8]}};
  {top} core(
    {(',' + chr(10) + '    ').join(conn)});
endmodule
"""
open(f'{out}/{top}_cfgwrap.v', 'w').write(wrap)


# ---- trained weights -> byte image
def parse_fixed(t):
    """'fixed<W,I..>' / 'ufixed<W,I..>' / 'int<W>' / 'uint<W>' (optionally with an ap_ prefix) -> (W, I, signed)"""
    t = t.replace('ap_', '').replace(' ', '')
    m = re.match(r'(u?)fixed<(\d+),(-?\d+)', t)
    if m:
        return int(m.group(2)), int(m.group(3)), m.group(1) == ''
    m = re.match(r'(u?)int<(\d+)', t)
    assert m, f'unsupported type {t}'
    return int(m.group(2)), int(m.group(2)), m.group(1) == ''


bits = np.zeros(NCFG, np.uint8)
for p in ports:
    ftxt = f'{prj}/firmware/weights/{p["name"]}.txt'
    if os.path.exists(ftxt):
        vals = np.array([float(v) for v in open(ftxt).read().replace(',', ' ').split()])
    else:
        txt = open(f'{prj}/firmware/weights/{p["name"]}.h').read()
        body = txt[txt.rindex('{', 0, txt.rindex('}')) + 1:txt.rindex('}')]
        vals = np.array([float(v) for v in body.split(',') if v.strip()])
    assert len(vals) == p['n'], (p['name'], len(vals))
    W, I, signed = parse_fixed(p['type'])
    raw = np.rint(vals * 2.0 ** (W - I)).astype(np.int64)
    assert np.array_equal(raw, vals * 2.0 ** (W - I)), f'{p["name"]}: values off the {p["type"]} grid'
    if signed:
        assert raw.min() >= -(1 << (W - 1)) and raw.max() < (1 << (W - 1))
    raw &= (1 << W) - 1
    lo = cmap[p['name']]['lo']
    for i, r in enumerate(raw):
        for b in range(W):
            bits[lo + W * i + b] = (int(r) >> b) & 1
by = np.packbits(bits.reshape(-1, 8)[:, ::-1], axis=1).ravel()      # byte k = cfg[8k+7:8k]
open(f'{out}/{top}_cfg.hex', 'w').write(''.join(f'{b:02x}\n' for b in by))
json.dump(dict(top=f'{top}_cfgwrap', core=top, n_cfg_bits=NCFG, n_weight_bits=ncfg, pad_bits=pad,
               n_bytes=NCFG // 8, load='cfg_we=1 for n_bytes cycles of ap_clk, first byte -> cfg[7:0]',
               ports=cmap), open(f'{out}/cfg_map.json', 'w'), indent=1)
print(f'{top}_cfgwrap: {NCFG} cfg flip-flops ({NCFG // 8} bytes), {len(others)} pass-through ports')

# ---- optional xsim testbench through the wrapper
if len(sys.argv) > 7:
    X = np.load(sys.argv[5]); Y = np.load(sys.argv[6]); N = int(sys.argv[7])
    defs = open(f'{prj}/firmware/defines.h').read()
    def idx(n):
        m = re.search(r'_(\d+)$', n); return int(m.group(1)) if m else -1
    din = [n for n in others if decl[n][0] == 'input' and not n.startswith('ap_') and not n.endswith('_ap_vld')]
    vin = [n for n in others if decl[n][0] == 'input' and n.endswith('_ap_vld')]
    outs = sorted([n for n in others if decl[n][0] == 'output' and not n.startswith('ap_') and not n.endswith('_ap_vld')], key=idx)
    ovld = [n for n in others if decl[n][0] == 'output' and n.endswith('_ap_vld')]
    it = re.search(r'typedef\s+(ap_u?fixed<[^>]+>)\s+input_t;', defs).group(1)
    rt = re.search(r'typedef\s+(ap_u?fixed<[^>]+>)\s+result_t;', defs).group(1)
    iW, iI, _ = parse_fixed(it); rW, rI, _ = parse_fixed(rt)
    Xf = X[:N].reshape(N, -1); NIN = Xf.shape[1]
    if len(din) == 1 and width(din[0]) == NIN * iW:          # one packed bus (element i at [iW*i +: iW])
        dconn = [(din[0], NIN * iW - 1, 0)]
    else:                                                       # split per element <in>_0 .. <in>_{NIN-1}
        din = sorted(din, key=idx)
        assert len(din) == NIN and [idx(n) for n in din] == list(range(NIN)), (len(din), NIN)
        assert all(width(n) == iW for n in din)
        dconn = [(n, iW * i + iW - 1, iW * i) for i, n in enumerate(din)]
    assert len(outs) == Y.reshape(len(Y), -1).shape[1], (outs, Y.shape)
    xr = np.rint(Xf * 2.0 ** (iW - iI)).astype(np.int64) & ((1 << iW) - 1)
    with open(f'{out}/tb_in.hex', 'w') as f:
        for row in xr:
            v = 0
            for i, r in enumerate(row):
                v |= int(r) << (iW * i)
            f.write(f'{v:0{(NIN * iW + 3) // 4}x}\n')
    np.savetxt(f'{out}/tb_expected.txt', np.rint(Y[:N].reshape(N, -1) * 2.0 ** (rW - rI)).astype(np.int64), fmt='%d')
    done = ovld[0] if ovld else 'ap_done'
    rst_assert = '1' if rst == 'ap_rst' else '0'
    pc = {n: f'.{n}({n})' for n in others}
    for n, hi, lo in dconn: pc[n] = f'.{n}(xbus[{hi}:{lo}])'
    for n in vin: pc[n] = f'.{n}(in_vld)'
    tb = f"""`timescale 1ns/1ps
// AUTO-GENERATED by make_cfgwrap.py: loads {top}_cfg.hex through cfg_we/cfg_din, then runs {N} events; writes raw
// result_t integers (one event per line) to tb_out.txt -> check with cosim_check.py --raw tb_out.txt <keras.npy> --frac-bits {rW - rI}
module tb_{top}_cfgwrap;
  reg ap_clk = 0; always #12.5 ap_clk = ~ap_clk;   // 25 ns
  reg {rst} = {rst_assert}; reg ap_start = 0; reg cfg_we = 0; reg [7:0] cfg_din = 0;
  reg [{NIN * iW - 1}:0] xbus = 0; reg in_vld = 0;
  wire ap_done, ap_idle, ap_ready;
{''.join(f'  wire [{width(o) - 1}:0] {o};{chr(10)}' for o in outs)}{''.join(f'  wire {o};{chr(10)}' for o in ovld)}
  reg [7:0] img [0:{NCFG // 8 - 1}];
  reg [{NIN * iW - 1}:0] xin [0:{N - 1}];
  integer k, e, fo, t;
  {top}_cfgwrap dut(
    {(',' + chr(10) + '    ').join([pc[n] for n in others] + ['.cfg_we(cfg_we)', '.cfg_din(cfg_din)'])});
  initial begin
    $readmemh("{top}_cfg.hex", img); $readmemh("tb_in.hex", xin);
    fo = $fopen("tb_out.txt", "w");
    repeat (4) @(posedge ap_clk);
    {rst} <= ~{rst};
    for (k = 0; k < {NCFG // 8}; k = k + 1) begin @(negedge ap_clk); cfg_we = 1; cfg_din = img[k]; end
    @(negedge ap_clk); cfg_we = 0;
    for (e = 0; e < {N}; e = e + 1) begin
      @(negedge ap_clk); xbus = xin[e]; in_vld = 1; ap_start = 1;
      t = 0;
      while (!{done} && t < 2000) begin @(posedge ap_clk); #1; if (ap_ready) begin ap_start = 0; in_vld = 0; end t = t + 1; end
      $fwrite(fo, {'"' + ' '.join(['%0d'] * len(outs)) + chr(92) + 'n"'}, {', '.join(f'$signed({o})' for o in outs)});
      ap_start = 0; in_vld = 0;
      repeat (2) @(negedge ap_clk);
    end
    $fclose(fo); $display("TB DONE %0d events", {N}); $finish;
  end
endmodule
"""
    open(f'{out}/tb_{top}_cfgwrap.v', 'w').write(tb)
    print('testbench written for', N, 'events; outputs', len(outs), 'inputs', 'bus' if len(dconn) == 1 else 'split')
